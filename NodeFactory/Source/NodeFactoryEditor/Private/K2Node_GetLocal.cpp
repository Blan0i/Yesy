const FName UK2Node_CNALocalVariableBase::ValuePinName(TEXT("Value"));

// UK2Node_CNALocalVariableBase

UK2Node_CNALocalVariableBase::UK2Node_CNALocalVariableBase(const FObjectInitializer& ObjectInitializer)
	: Super(ObjectInitializer)
{
	CachedVariableType.PinCategory = UEdGraphSchema_K2::PC_Wildcard;
}

UCustomNodeAsset* UK2Node_CNALocalVariableBase::GetOwningAsset() const
{
	return FCNAGraphUtils::GetOwningAsset(this);
}

const FCNALocalVariable* UK2Node_CNALocalVariableBase::FindVariable() const
{
	const UCustomNodeAsset* Asset = GetOwningAsset();
	return Asset ? Asset->FindLocalVariable(VariableGuid, VariableName) : nullptr;
}

FEdGraphPinType UK2Node_CNALocalVariableBase::GetVariableType() const
{
	if (const FCNALocalVariable* Variable = FindVariable())
	{
		return Variable->Type;
	}
	return CachedVariableType;
}

FText UK2Node_CNALocalVariableBase::GetVariableDisplayName() const
{
	if (const FCNALocalVariable* Variable = FindVariable())
	{
		return FText::FromName(Variable->Name);
	}
	return VariableName.IsNone() ? LOCTEXT("LocalVariableNone", "<none>") : FText::FromName(VariableName);
}

void UK2Node_CNALocalVariableBase::SyncCacheFromVariable()
{
	if (const FCNALocalVariable* Variable = FindVariable())
	{
		VariableGuid = Variable->Guid;
		VariableName = Variable->Name;
		CachedVariableType = Variable->Type;
	}
}

void UK2Node_CNALocalVariableBase::InitVariable(const FCNALocalVariable& Variable)
{
	VariableGuid = Variable.Guid;
	VariableName = Variable.Name;
	CachedVariableType = Variable.Type;
}

void UK2Node_CNALocalVariableBase::SetVariable(const FCNALocalVariable& Variable)
{
	if (Variable.Guid == VariableGuid && Variable.Name == VariableName)
	{
		return;
	}
	const FScopedTransaction Transaction(LOCTEXT("ChangeLocalVariableTransaction", "Change Local Variable"));
	Modify();
	InitVariable(Variable);
	ReconstructNode();
	if (UBlueprint* Blueprint = FCNAGraphUtils::GetBlueprint(this))
	{
		FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	}
}

void UK2Node_CNALocalVariableBase::GetSelectableVariables(TArray<const FCNALocalVariable*>& OutVariables) const
{
	if (const UCustomNodeAsset* Asset = GetOwningAsset())
	{
		for (const FCNALocalVariable& Variable : Asset->LocalVariables)
		{
			OutVariables.Add(&Variable);
		}
	}
}

UEdGraphPin* UK2Node_CNALocalVariableBase::CreateValuePin(EEdGraphPinDirection Direction, FName PinName)
{
	const FEdGraphPinType Type = GetVariableType();
	UEdGraphPin* Pin = CreatePin(Direction, Type, PinName);
	if (Direction == EGPD_Input)
	{
		GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValueBasedOnType(Pin);
	}
	return Pin;
}

void UK2Node_CNALocalVariableBase::ReconstructNode()
{
	// A missing variable keeps the pins and wires; the custom node reports CNA017 when it compiles.
	if (!FindVariable() && Pins.Num() > 0)
	{
		return;
	}
	SyncCacheFromVariable();
	Super::ReconstructNode();
}

FLinearColor UK2Node_CNALocalVariableBase::GetNodeTitleColor() const
{
	// Like variable nodes: the color of the type.
	return FCNAPinUtils::GetTypeColor(GetVariableType());
}

FSlateIcon UK2Node_CNALocalVariableBase::GetIconAndTint(FLinearColor& OutColor) const
{
	OutColor = FCNAPinUtils::GetTypeColor(GetVariableType());
	return FSlateIcon(FEditorStyle::GetStyleSetName(), TEXT("Kismet.AllClasses.VariableIcon"));
}

bool UK2Node_CNALocalVariableBase::IsCompatibleWithGraph(const UEdGraph* TargetGraph) const
{
	if (!Super::IsCompatibleWithGraph(TargetGraph))
	{
		return false;
	}
	// Only inside the Execution Graph of a Custom Node Asset (spec 4.8, item 2).
	const UCustomNodeAsset* GraphOwner = FCNAGraphUtils::GetExecuteGraphOwner(TargetGraph);
	if (!GraphOwner)
	{
		return false;
	}
	// A menu entry is bound to a variable of one asset.
	if (VariableGuid.IsValid())
	{
		return GraphOwner->FindLocalVariable(VariableGuid) != nullptr;
	}
	return true;
}

void UK2Node_CNALocalVariableBase::GetContextMenuActions(const FGraphNodeContextMenuBuilder& Context) const
{
	Super::GetContextMenuActions(Context);
	if (Context.bIsDebugging || !Context.MenuBuilder)
	{
		return;
	}

	TArray<const FCNALocalVariable*> Variables;
	GetSelectableVariables(Variables);
	if (Variables.Num() == 0)
	{
		return;
	}

	TWeakObjectPtr<UK2Node_CNALocalVariableBase> WeakNode(const_cast<UK2Node_CNALocalVariableBase*>(this));
	Context.MenuBuilder->BeginSection(TEXT("CNALocalVariable"), LOCTEXT("LocalVariableMenuSection", "Local Variable"));
	for (const FCNALocalVariable* Variable : Variables)
	{
		const FGuid Guid = Variable->Guid;
		Context.MenuBuilder->AddMenuEntry(
			FText::Format(LOCTEXT("UseVariableMenu", "Use {0}"), FText::FromName(Variable->Name)),
			FText::Format(LOCTEXT("UseVariableMenuTooltip", "Reference the local variable {0} ({1})."), FText::FromName(Variable->Name), FCNAPinUtils::GetTypeText(Variable->Type)),
			FSlateIcon(),
			FUIAction(
				FExecuteAction::CreateLambda([WeakNode, Guid]()
				{
					UK2Node_CNALocalVariableBase* Node = WeakNode.Get();
					const UCustomNodeAsset* Asset = Node ? Node->GetOwningAsset() : nullptr;
					if (const FCNALocalVariable* Target = Asset ? Asset->FindLocalVariable(Guid) : nullptr)
					{
						Node->SetVariable(*Target);
					}
				}),
				FCanExecuteAction(),
				FIsActionChecked::CreateLambda([WeakNode, Guid]()
				{
					const UK2Node_CNALocalVariableBase* Node = WeakNode.Get();
					return Node && Node->VariableGuid == Guid;
				})),
			NAME_None,
			EUserInterfaceActionType::RadioButton);
	}
	Context.MenuBuilder->EndSection();
}

void UK2Node_CNALocalVariableBase::PostPasteNode()
{
	Super::PostPasteNode();
	// Pasted into another asset: the Guid is unknown there, the name may still match a variable.
	const UCustomNodeAsset* Asset = GetOwningAsset();
	if (Asset && !Asset->FindLocalVariable(VariableGuid))
	{
		if (const FCNALocalVariable* ByName = Asset->FindLocalVariableByName(VariableName))
		{
			InitVariable(*ByName);
		}
	}
}

FText UK2Node_CNALocalVariableBase::GetKeywords() const
{
	return LOCTEXT("LocalVariableKeywords", "local variable temp temporary");
}

FText UK2Node_CNALocalVariableBase::GetMenuCategory() const
{
	return LOCTEXT("LocalVariablesMenuCategory", "Local Variables");
}

void UK2Node_CNALocalVariableBase::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);
	// FCNAExpander replaces the node and leaves it without wires. A wired node here was pasted into a graph that is
	// not the Execution Graph of a Custom Node Asset; an unwired one has no effect and is pruned by the compiler.
	const bool bHasWires = Pins.ContainsByPredicate([](const UEdGraphPin* Pin) { return Pin && Pin->LinkedTo.Num() > 0; });
	if (bHasWires)
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("LocalOutsideAsset", "@@ can only be used inside the Execution Graph of a Custom Node Asset.").ToString(), this);
		BreakAllNodeLinks();
	}
}

// UK2Node_GetLocal

UK2Node_GetLocal::UK2Node_GetLocal(const FObjectInitializer& ObjectInitializer)
	: Super(ObjectInitializer)
{
}

UEdGraphPin* UK2Node_GetLocal::GetValuePin() const
{
	return FindPin(ValuePinName, EGPD_Output);
}

void UK2Node_GetLocal::AllocateDefaultPins()
{
	SyncCacheFromVariable();
	UEdGraphPin* Pin = CreateValuePin(EGPD_Output, ValuePinName);
	if (Pin)
	{
		Pin->PinFriendlyName = GetVariableDisplayName();
		if (const FCNALocalVariable* Variable = FindVariable())
		{
			Pin->PinToolTip = Variable->Tooltip.ToString();
		}
	}
	Super::AllocateDefaultPins();
}

FText UK2Node_GetLocal::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	if (TitleType == ENodeTitleType::MenuTitle)
	{
		return FText::Format(LOCTEXT("GetLocalMenuTitle", "Get {0}"), GetVariableDisplayName());
	}
	if (TitleType == ENodeTitleType::FullTitle)
	{
		return FText::Format(LOCTEXT("GetLocalFullTitle", "Get {0}\nLocal Variable"), GetVariableDisplayName());
	}
	return FText::Format(LOCTEXT("GetLocalTitle", "Get {0}"), GetVariableDisplayName());
}

FText UK2Node_GetLocal::GetTooltipText() const
{
	const FCNALocalVariable* Variable = FindVariable();
	if (!Variable)
	{
		return FText::Format(LOCTEXT("GetLocalMissingTooltip", "The local variable {0} does not exist in this asset (CNA017)."), GetVariableDisplayName());
	}
	FText Description = Variable->Tooltip.IsEmpty() ? LOCTEXT("GetLocalNoTooltip", "Reads the local variable of this node instance.") : Variable->Tooltip;
	return FText::Format(LOCTEXT("GetLocalTooltip", "Get {0} ({1})\n{2}"), FText::FromName(Variable->Name), FCNAPinUtils::GetTypeText(Variable->Type), Description);
}

void UK2Node_GetLocal::GetMenuActions(FBlueprintActionDatabaseRegistrar& ActionRegistrar) const
{
	FCNANodeMenu::RegisterLocalVariableActions(ActionRegistrar, GetClass());
}

